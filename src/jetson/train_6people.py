rng = np.random.default_rng(1209)


def augment(j, rng):
    """(N,T,21,3) 정규화 좌표 증강. 반전/회전은 시퀀스 단위로 동일하게."""
    j = j.copy(); n = len(j)
    flip = rng.random(n) < 0.5
    j[flip, ..., 0] *= -1                                    # 좌우 반전 (각도는 불변)
    th = rng.uniform(-np.pi/9, np.pi/9, size=n).astype(np.float32)
    cs, sn = np.cos(th)[:, None, None], np.sin(th)[:, None, None]
    x, y = j[..., 0], j[..., 1]
    j[..., 0], j[..., 1] = cs*x - sn*y, sn*x + cs*y          # 화면 내 회전 +-20도
    j *= rng.uniform(0.9, 1.1, size=(n, 1, 1, 1)).astype(np.float32)
    j += rng.normal(0, 0.02, size=j.shape).astype(np.float32)
    return j


def to_features(raw, aug_rng=None):
    if FEAT_MODE == 'legacy':
        return raw[..., :99].astype(np.float32)
    # 수집 해상도의 화면비로 편다 (hand_feature.COLLECT_ASPECT 기본값)
    jn = normalize_joints(joints_from_raw(raw))
    if aug_rng is not None:
        jn = augment(jn, aug_rng)
    return make_feature(jn, already_normalized=True).astype(np.float32)


def labels_of(raw):
    return raw[:, 0, -1].astype(np.int64)


FEATURE_DIM = 78 if FEAT_MODE == 'norm' else 99
