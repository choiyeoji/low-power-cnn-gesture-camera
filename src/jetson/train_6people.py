from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, LSTM, Dense, Dropout
from tensorflow.keras.callbacks import ModelCheckpoint, ReduceLROnPlateau, EarlyStopping
from tensorflow.keras.utils import to_categorical


def build_model(feature_dim):
    m = Sequential([
        Input(shape=(SEQ_LENGTH, feature_dim)),
        LSTM(64, return_sequences=True),
        Dropout(0.3),
        LSTM(64),
        Dropout(0.3),
        Dense(32, activation='relu'),
        Dropout(0.2),
        Dense(len(ACTIONS), activation='softmax'),
    ])
    m.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['acc'])
    return m


build_model(FEATURE_DIM).summary()

from sklearn.model_selection import train_test_split


def fit_eval(x_tr, y_tr, x_va, y_va, tag, epochs=100):
    model = build_model(x_tr.shape[-1])
    model.fit(x_tr, to_categorical(y_tr, len(ACTIONS)),
              validation_data=(x_va, to_categorical(y_va, len(ACTIONS))),
              epochs=epochs, batch_size=128, verbose=0,
              callbacks=[
                  EarlyStopping(monitor='val_acc', mode='max', patience=20,
                                restore_best_weights=True),
                  ReduceLROnPlateau(monitor='val_acc', mode='max',
                                    factor=0.5, patience=8, min_lr=1e-5),
              ])
    acc = (model.predict(x_va, verbose=0).argmax(1) == y_va).mean()
    print(f'{tag:32s} val acc = {acc*100:6.2f}%')
    return acc


